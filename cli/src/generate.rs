use crate::preset::{Preset, packages_for, shared_systems};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

const NIXPKGS_INPUT: &str = "github:NixOS/nixpkgs/nixpkgs-unstable";
const PLAINIX_INPUT: &str = "github:yawarakatai/plainix";
const PACKAGE_SEARCH_URL: &str = "https://search.nixos.org/packages?channel=unstable";

#[derive(Debug)]
pub struct InitResult {
    pub presets: Vec<Preset>,
    pub packages: Vec<&'static str>,
    pub systems: Vec<&'static str>,
    pub envrc: EnvrcResult,
    pub gitignore: GitignoreResult,
    pub git: GitResult,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EnvrcResult {
    Created,
    KeptExisting,
}

#[derive(Debug, Eq, PartialEq)]
pub enum GitignoreResult {
    NotApplicable,
    Created,
    Updated,
    AlreadyPresent,
    Failed(String),
}

#[derive(Debug)]
pub enum GitResult {
    NotRepository,
    Prepared {
        files: Vec<&'static str>,
    },
    Manual {
        files: Vec<&'static str>,
        error: String,
    },
}

pub fn check_directory(directory: &Path) -> Result<(), String> {
    let conflicts = ["plainix.nix", "flake.nix", "flake.lock"]
        .into_iter()
        .map(|file| directory.join(file))
        .filter(|path| path.exists())
        .collect::<Vec<_>>();
    if conflicts.is_empty() {
        return Ok(());
    }

    let paths = conflicts
        .iter()
        .map(|path| format!("`{}`", path.display()))
        .collect::<Vec<_>>()
        .join(", ");
    Err(format!(
        "Plainix: refusing to overwrite {paths}; remove or move the existing files first"
    ))
}

pub fn initialize(directory: &Path, presets: &[Preset]) -> Result<InitResult, String> {
    initialize_with_lock(directory, is_git_repository(directory), presets, lock_flake)
}

fn initialize_with_lock<F>(
    directory: &Path,
    git_repository: bool,
    presets: &[Preset],
    lock: F,
) -> Result<InitResult, String>
where
    F: FnOnce(&Path) -> Result<(), String>,
{
    check_directory(directory)?;

    let plainix_path = directory.join("plainix.nix");
    let flake_path = directory.join("flake.nix");
    let lock_path = directory.join("flake.lock");
    let envrc_path = directory.join(".envrc");
    let packages = packages_for(presets);
    let systems = shared_systems(presets);
    let create_envrc = !envrc_path.exists();
    let envrc = if create_envrc {
        EnvrcResult::Created
    } else {
        EnvrcResult::KeptExisting
    };
    let mut generated_paths = vec![plainix_path.clone(), flake_path.clone(), lock_path.clone()];
    let mut git_files = vec!["plainix.nix", "flake.nix", "flake.lock"];
    if create_envrc {
        generated_paths.push(envrc_path.clone());
        git_files.push(".envrc");
    }
    let write_result = (|| {
        write_atomic(
            &plainix_path,
            render_plainix(&systems, presets, &packages).as_bytes(),
        )?;
        write_atomic(&flake_path, render_flake().as_bytes())?;
        if create_envrc {
            write_atomic(&envrc_path, b"# Generated by Plainix\nuse flake\n")?;
        }
        Ok(())
    })();

    if let Err(error) = write_result {
        return Err(with_cleanup(error, &generated_paths));
    }
    if let Err(error) = lock(directory) {
        return Err(with_cleanup(error, &generated_paths));
    }

    let gitignore = if git_repository {
        match ensure_gitignore(&directory.join(".gitignore")) {
            Ok(result @ (GitignoreResult::Created | GitignoreResult::Updated)) => {
                git_files.push(".gitignore");
                result
            }
            Ok(result) => result,
            Err(error) => GitignoreResult::Failed(error),
        }
    } else {
        GitignoreResult::NotApplicable
    };
    let git = if git_repository {
        prepare_git_files(directory, &git_files)
    } else {
        GitResult::NotRepository
    };

    Ok(InitResult {
        presets: presets.to_vec(),
        packages,
        systems,
        envrc,
        gitignore,
        git,
    })
}

fn ensure_gitignore(path: &Path) -> Result<GitignoreResult, String> {
    let existing = match fs::read(path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            write_atomic(path, b".direnv/\n")?;
            return Ok(GitignoreResult::Created);
        }
        Err(error) => {
            return Err(format!(
                "Plainix: could not read `{}`: {error}",
                path.display()
            ));
        }
    };

    let text = std::str::from_utf8(&existing).map_err(|error| {
        format!(
            "Plainix: could not update `{}` because it is not UTF-8: {error}",
            path.display()
        )
    })?;
    if text.lines().any(is_direnv_ignored) {
        return Ok(GitignoreResult::AlreadyPresent);
    }

    let mut contents = existing;
    if !contents.is_empty() && !contents.ends_with(b"\n") {
        contents.push(b'\n');
    }
    contents.extend_from_slice(b".direnv/\n");
    write_atomic(path, &contents)?;
    Ok(GitignoreResult::Updated)
}

fn is_direnv_ignored(line: &str) -> bool {
    matches!(
        line.trim(),
        ".direnv" | ".direnv/" | "/.direnv" | "/.direnv/"
    )
}

fn with_cleanup(error: String, generated_paths: &[PathBuf]) -> String {
    let cleanup_errors = generated_paths
        .iter()
        .rev()
        .filter_map(|path| match fs::remove_file(path) {
            Ok(()) => None,
            Err(remove_error) if remove_error.kind() == io::ErrorKind::NotFound => None,
            Err(remove_error) => Some(format!(
                "could not remove `{}`: {remove_error}",
                path.display()
            )),
        })
        .collect::<Vec<_>>();

    if cleanup_errors.is_empty() {
        error
    } else {
        format!(
            "{error}\nPlainix: cleanup was incomplete: {}",
            cleanup_errors.join("; ")
        )
    }
}

fn write_atomic(path: &Path, contents: &[u8]) -> Result<(), String> {
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| format!("Plainix: invalid output path `{}`", path.display()))?;
    let temporary = path.with_file_name(format!(".{file_name}.plainix-{}.tmp", std::process::id()));

    if let Err(error) = fs::write(&temporary, contents) {
        let _ = fs::remove_file(&temporary);
        return Err(format!(
            "Plainix: could not write temporary file `{}`: {error}",
            temporary.display()
        ));
    }
    if let Err(error) = fs::rename(&temporary, path) {
        let _ = fs::remove_file(&temporary);
        return Err(format!(
            "Plainix: could not replace `{}`: {error}",
            path.display()
        ));
    }
    Ok(())
}

fn is_git_repository(directory: &Path) -> bool {
    Command::new("git")
        .args(["-C"])
        .arg(directory)
        .args(["rev-parse", "--is-inside-work-tree"])
        .output()
        .is_ok_and(|output| output.status.success())
}

fn prepare_git_files(directory: &Path, files: &[&'static str]) -> GitResult {
    let output = Command::new("git")
        .args(["-C"])
        .arg(directory)
        .args(["add", "--intent-to-add", "--force", "--"])
        .args(files)
        .output();

    match output {
        Ok(output) if output.status.success() => GitResult::Prepared {
            files: files.to_vec(),
        },
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr).trim().to_owned();
            let error = if stderr.is_empty() {
                format!("git add exited with {}", output.status)
            } else {
                stderr
            };
            GitResult::Manual {
                files: files.to_vec(),
                error,
            }
        }
        Err(error) => GitResult::Manual {
            files: files.to_vec(),
            error: error.to_string(),
        },
    }
}

// Locking only needs flake.nix. Running it in the project would copy the whole
// directory, including any large assets, into the Nix store.
fn lock_flake(directory: &Path) -> Result<(), String> {
    let workspace = std::env::temp_dir().join(format!("plainix-lock-{}", std::process::id()));
    fs::create_dir(&workspace).map_err(|error| {
        format!(
            "Plainix: could not create `{}`: {error}",
            workspace.display()
        )
    })?;
    let result = lock_in_workspace(directory, &workspace);
    let _ = fs::remove_dir_all(&workspace);
    result
}

fn lock_in_workspace(directory: &Path, workspace: &Path) -> Result<(), String> {
    fs::copy(directory.join("flake.nix"), workspace.join("flake.nix"))
        .map_err(|error| format!("Plainix: could not prepare locking: {error}"))?;

    eprintln!("Creating flake.lock with Nix (this may take a moment)...");
    let status = Command::new("nix")
        .args(["flake", "lock", "path:."])
        .current_dir(workspace)
        .status()
        .map_err(|error| {
            format!(
                "Plainix: could not run `nix flake lock`: {error}\nInstall Nix and enable `nix-command` and `flakes`, then try again."
            )
        })?;

    if !status.success() {
        return Err(format!(
            "Plainix: `nix flake lock` failed with {status}. See the Nix output above.\nEnsure Nix has `experimental-features = nix-command flakes` enabled."
        ));
    }

    let lock = fs::read(workspace.join("flake.lock")).map_err(|error| {
        format!("Plainix: `nix flake lock` did not produce a readable `flake.lock`: {error}")
    })?;
    write_atomic(&directory.join("flake.lock"), &lock)
}

fn render_list(values: &[&str]) -> String {
    if values.is_empty() {
        return "[ ]".to_owned();
    }
    let lines = values
        .iter()
        .map(|value| format!("    \"{value}\""))
        .collect::<Vec<_>>()
        .join("\n");
    format!("[\n{lines}\n  ]")
}

fn render_plainix(systems: &[&str], presets: &[Preset], packages: &[&str]) -> String {
    let tools = if presets.is_empty() {
        String::new()
    } else {
        format!(
            "# Initial tools: {}\n",
            presets
                .iter()
                .map(|preset| preset.name)
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let systems = render_list(systems);
    let packages = render_list(packages);

    format!(
        "{tools}# Package source: {NIXPKGS_INPUT} (pinned in flake.lock)\n# Find package names: {PACKAGE_SEARCH_URL}\n\n{{\n  systems = {systems};\n\n  packages = {packages};\n}}\n"
    )
}

fn render_flake() -> String {
    format!(
        "{{\n  description = \"Project environment generated by Plainix\";\n\n  inputs.nixpkgs.url = \"{NIXPKGS_INPUT}\";\n  inputs.plainix = {{\n    url = \"{PLAINIX_INPUT}\";\n    inputs.nixpkgs.follows = \"nixpkgs\";\n  }};\n\n  outputs = inputs:\n    inputs.plainix.lib.project inputs ./plainix.nix;\n}}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn temporary_directory(name: &str) -> PathBuf {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path = std::env::temp_dir().join(format!("plainix-generate-{name}-{unique}"));
        fs::create_dir_all(&path).unwrap();
        path
    }

    fn preset(id: &str) -> Preset {
        *crate::preset::PRESETS
            .iter()
            .find(|preset| preset.id == id)
            .unwrap()
    }

    #[test]
    fn generates_selected_tools_and_lock() {
        let directory = temporary_directory("success");
        let rust = preset("rust");

        let result = initialize_with_lock(&directory, false, &[rust], |path| {
            fs::write(path.join("flake.lock"), "{}\n").map_err(|error| error.to_string())
        })
        .unwrap();

        let plainix = fs::read_to_string(directory.join("plainix.nix")).unwrap();
        assert_eq!(result.presets, vec![rust]);
        assert_eq!(result.envrc, EnvrcResult::Created);
        assert_eq!(result.gitignore, GitignoreResult::NotApplicable);
        assert!(matches!(result.git, GitResult::NotRepository));
        assert!(!directory.join(".gitignore").exists());
        assert!(plainix.contains("# Initial tools: Rust"));
        assert!(plainix.contains("\"aarch64-darwin\""));
        assert!(plainix.contains("\"rustc\""));
        assert!(plainix.contains(NIXPKGS_INPUT));
        assert!(plainix.contains(PACKAGE_SEARCH_URL));
        assert!(directory.join("flake.lock").is_file());
        assert_eq!(
            fs::read_to_string(directory.join(".envrc")).unwrap(),
            "# Generated by Plainix\nuse flake\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn limits_systems_to_those_every_preset_supports() {
        let directory = temporary_directory("systems");

        let result = initialize_with_lock(
            &directory,
            false,
            &[preset("rust"), preset("freecad")],
            |path| fs::write(path.join("flake.lock"), "{}\n").map_err(|error| error.to_string()),
        )
        .unwrap();

        assert_eq!(result.systems, vec!["x86_64-linux", "aarch64-linux"]);
        assert!(
            !fs::read_to_string(directory.join("plainix.nix"))
                .unwrap()
                .contains("aarch64-darwin")
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn removes_generated_files_when_locking_fails() {
        let directory = temporary_directory("rollback");

        let error = initialize_with_lock(&directory, false, &[], |_| Err("lock failed".to_owned()))
            .unwrap_err();

        assert_eq!(error, "lock failed");
        for file in ["plainix.nix", "flake.nix", "flake.lock", ".envrc"] {
            assert!(!directory.join(file).exists());
        }
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn refuses_to_replace_existing_project_files() {
        let directory = temporary_directory("existing");
        fs::write(directory.join("plainix.nix"), "original project\n").unwrap();

        let error = initialize_with_lock(&directory, false, &[], |_| {
            panic!("lock must not run when a project file already exists")
        })
        .unwrap_err();

        assert!(error.contains("refusing to overwrite"));
        assert_eq!(
            fs::read_to_string(directory.join("plainix.nix")).unwrap(),
            "original project\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn preserves_existing_envrc() {
        let directory = temporary_directory("envrc");
        fs::write(directory.join(".envrc"), "source_env custom.envrc\n").unwrap();

        let result = initialize_with_lock(&directory, false, &[], |path| {
            fs::write(path.join("flake.lock"), "{}\n").map_err(|error| error.to_string())
        })
        .unwrap();

        assert_eq!(result.envrc, EnvrcResult::KeptExisting);
        assert!(result.packages.is_empty());
        assert!(
            fs::read_to_string(directory.join("plainix.nix"))
                .unwrap()
                .contains("packages = [ ];")
        );
        assert_eq!(
            fs::read_to_string(directory.join(".envrc")).unwrap(),
            "source_env custom.envrc\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn prepares_git_files_without_staging_contents() {
        let directory = temporary_directory("git");
        assert!(
            Command::new("git")
                .args(["init", "--quiet"])
                .current_dir(&directory)
                .output()
                .unwrap()
                .status
                .success()
        );
        fs::write(directory.join(".gitignore"), "/target\n").unwrap();

        let result = initialize_with_lock(&directory, true, &[], |path| {
            fs::write(path.join("flake.lock"), "{}\n").map_err(|error| error.to_string())
        })
        .unwrap();

        let GitResult::Prepared { files } = result.git else {
            panic!("expected generated files to be prepared for Git");
        };
        for file in [
            "plainix.nix",
            "flake.nix",
            "flake.lock",
            ".envrc",
            ".gitignore",
        ] {
            assert!(files.contains(&file));
            assert!(
                Command::new("git")
                    .args(["ls-files", "--error-unmatch", "--", file])
                    .current_dir(&directory)
                    .output()
                    .unwrap()
                    .status
                    .success()
            );
        }
        assert!(
            Command::new("git")
                .args(["diff", "--cached", "--quiet"])
                .current_dir(&directory)
                .output()
                .unwrap()
                .status
                .success()
        );
        assert!(
            fs::read_to_string(directory.join(".gitignore"))
                .unwrap()
                .contains(".direnv/\n")
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn updates_gitignore_once() {
        let directory = temporary_directory("gitignore");
        let path = directory.join(".gitignore");
        fs::write(&path, "/target").unwrap();

        assert_eq!(ensure_gitignore(&path).unwrap(), GitignoreResult::Updated);
        assert_eq!(fs::read_to_string(&path).unwrap(), "/target\n.direnv/\n");
        assert_eq!(
            ensure_gitignore(&path).unwrap(),
            GitignoreResult::AlreadyPresent
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn leaves_gitignore_unchanged_when_locking_fails() {
        let directory = temporary_directory("gitignore-rollback");
        let path = directory.join(".gitignore");
        fs::write(&path, "/target\n").unwrap();

        let error = initialize_with_lock(&directory, true, &[], |_| Err("lock failed".to_owned()))
            .unwrap_err();

        assert_eq!(error, "lock failed");
        assert_eq!(fs::read_to_string(path).unwrap(), "/target\n");
        fs::remove_dir_all(directory).unwrap();
    }
}
