use crate::detect::{ProjectKind, current_system, detect_projects};
use crate::preset::packages_for;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

const NIXPKGS_INPUT: &str = "github:NixOS/nixpkgs/nixos-unstable";
const PLAINIX_INPUT: &str = "github:yawarakatai/plainix";
const PACKAGE_SEARCH_URL: &str = "https://search.nixos.org/packages?channel=unstable";

#[derive(Clone, Copy, Debug, Default)]
pub struct InitOptions {
    pub direnv: bool,
}

#[derive(Debug)]
pub struct InitResult {
    pub projects: Vec<ProjectKind>,
    pub packages: Vec<&'static str>,
    pub system: &'static str,
    pub envrc: EnvrcResult,
    pub untracked_files: Vec<&'static str>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EnvrcResult {
    NotRequested,
    Created,
    KeptExisting,
}

pub fn initialize(directory: &Path, options: InitOptions) -> Result<InitResult, String> {
    initialize_with_lock(directory, options, lock_flake)
}

fn initialize_with_lock<F>(
    directory: &Path,
    options: InitOptions,
    lock: F,
) -> Result<InitResult, String>
where
    F: FnOnce(&Path) -> Result<(), String>,
{
    let plainix_path = directory.join("plainix.nix");
    let flake_path = directory.join("flake.nix");
    let lock_path = directory.join("flake.lock");
    let envrc_path = directory.join(".envrc");

    let conflicts: Vec<_> = [&plainix_path, &flake_path, &lock_path]
        .into_iter()
        .filter(|path| path.exists())
        .collect();
    if !conflicts.is_empty() {
        let paths = conflicts
            .iter()
            .map(|path| format!("`{}`", path.display()))
            .collect::<Vec<_>>()
            .join(", ");
        return Err(format!(
            "Plainix: refusing to overwrite {paths}; remove or move the existing files first"
        ));
    }

    let projects = detect_projects(directory);
    let packages = packages_for(&projects);
    let system = current_system(std::env::consts::ARCH, std::env::consts::OS)?;
    let create_envrc = options.direnv && !envrc_path.exists();
    let envrc = if !options.direnv {
        EnvrcResult::NotRequested
    } else if create_envrc {
        EnvrcResult::Created
    } else {
        EnvrcResult::KeptExisting
    };

    let mut generated_paths = vec![plainix_path.clone(), flake_path.clone(), lock_path.clone()];
    if create_envrc {
        generated_paths.push(envrc_path.clone());
    }

    let write_result = (|| {
        write_atomic(&plainix_path, render_plainix(system, &packages).as_bytes())?;
        write_atomic(&flake_path, render_flake().as_bytes())?;
        if create_envrc {
            write_atomic(&envrc_path, b"# Generated by Plainix\nuse flake\n")?;
        }
        Ok(())
    })();

    if let Err(error) = write_result {
        return Err(with_cleanup(error, &generated_paths));
    }
    if let Err(error) = lock(directory) {
        return Err(with_cleanup(error, &generated_paths));
    }
    if !lock_path.is_file() {
        return Err(with_cleanup(
            "Plainix: `nix flake lock` succeeded without creating `flake.lock`".to_owned(),
            &generated_paths,
        ));
    }

    let mut generated_files = vec!["plainix.nix", "flake.nix", "flake.lock"];
    if create_envrc {
        generated_files.push(".envrc");
    }
    let untracked_files = untracked_git_files(directory, &generated_files);

    Ok(InitResult {
        projects,
        packages,
        system,
        envrc,
        untracked_files,
    })
}

fn with_cleanup(error: String, generated_paths: &[PathBuf]) -> String {
    let cleanup_errors = generated_paths
        .iter()
        .rev()
        .filter_map(|path| match fs::remove_file(path) {
            Ok(()) => None,
            Err(remove_error) if remove_error.kind() == io::ErrorKind::NotFound => None,
            Err(remove_error) => Some(format!(
                "could not remove `{}`: {remove_error}",
                path.display()
            )),
        })
        .collect::<Vec<_>>();

    if cleanup_errors.is_empty() {
        error
    } else {
        format!(
            "{error}\nPlainix: cleanup was incomplete: {}",
            cleanup_errors.join("; ")
        )
    }
}

fn write_atomic(path: &Path, contents: &[u8]) -> Result<(), String> {
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| format!("Plainix: invalid output path `{}`", path.display()))?;
    let temporary = path.with_file_name(format!(".{file_name}.plainix-{}.tmp", std::process::id()));

    fs::write(&temporary, contents).map_err(|error| {
        format!(
            "Plainix: could not write temporary file `{}`: {error}",
            temporary.display()
        )
    })?;
    if let Err(error) = fs::rename(&temporary, path) {
        let _ = fs::remove_file(&temporary);
        return Err(format!(
            "Plainix: could not replace `{}`: {error}",
            path.display()
        ));
    }
    Ok(())
}

fn untracked_git_files(directory: &Path, generated_files: &[&'static str]) -> Vec<&'static str> {
    let in_git_repository = Command::new("git")
        .args(["-C"])
        .arg(directory)
        .args(["rev-parse", "--is-inside-work-tree"])
        .output()
        .is_ok_and(|output| output.status.success());

    if !in_git_repository {
        return Vec::new();
    }

    generated_files
        .iter()
        .copied()
        .filter(|file| {
            !Command::new("git")
                .args(["-C"])
                .arg(directory)
                .args(["ls-files", "--error-unmatch", "--", file])
                .output()
                .is_ok_and(|output| output.status.success())
        })
        .collect()
}

fn lock_flake(directory: &Path) -> Result<(), String> {
    let output = Command::new("nix")
        .args(["flake", "lock", "path:."])
        .current_dir(directory)
        .output()
        .map_err(|error| {
            format!(
                "Plainix: could not run `nix flake lock`: {error}\nInstall Nix and enable `nix-command` and `flakes`, then try again."
            )
        })?;

    if output.status.success() {
        return Ok(());
    }

    let stderr = String::from_utf8_lossy(&output.stderr);
    Err(format!(
        "Plainix: `nix flake lock` failed:\n{}\nEnsure Nix has `experimental-features = nix-command flakes` enabled.",
        stderr.trim()
    ))
}

fn render_plainix(system: &str, packages: &[&str]) -> String {
    let packages = if packages.is_empty() {
        "[ ]".to_owned()
    } else {
        let package_lines = packages
            .iter()
            .map(|package| format!("    \"{package}\""))
            .collect::<Vec<_>>()
            .join("\n");
        format!("[\n{package_lines}\n  ]")
    };

    format!(
        "# Package source: {NIXPKGS_INPUT} (pinned in flake.lock)\n# Find package names: {PACKAGE_SEARCH_URL}\n\n{{\n  systems = [ \"{system}\" ];\n\n  packages = {packages};\n}}\n"
    )
}

fn render_flake() -> String {
    format!(
        "{{\n  description = \"Project environment generated by Plainix\";\n\n  inputs.nixpkgs.url = \"{NIXPKGS_INPUT}\";\n  inputs.plainix = {{\n    url = \"{PLAINIX_INPUT}\";\n    inputs.nixpkgs.follows = \"nixpkgs\";\n  }};\n\n  outputs = inputs:\n    inputs.plainix.lib.project inputs ./plainix.nix;\n}}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn temporary_directory(name: &str) -> PathBuf {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path = std::env::temp_dir().join(format!("plainix-generate-{name}-{unique}"));
        fs::create_dir_all(&path).unwrap();
        path
    }

    #[test]
    fn generates_rust_project_and_lock() {
        let directory = temporary_directory("success");
        fs::write(
            directory.join("Cargo.toml"),
            "[package]\nname = \"hello\"\n",
        )
        .unwrap();

        let result = initialize_with_lock(&directory, InitOptions { direnv: true }, |path| {
            fs::write(path.join("flake.lock"), "{}\n").map_err(|error| error.to_string())
        })
        .unwrap();

        let plainix = fs::read_to_string(directory.join("plainix.nix")).unwrap();
        assert_eq!(result.projects, vec![ProjectKind::Rust]);
        assert!(plainix.contains("\"rustc\""));
        assert!(plainix.contains(NIXPKGS_INPUT));
        assert!(plainix.contains(PACKAGE_SEARCH_URL));
        assert!(directory.join("flake.lock").is_file());
        assert_eq!(
            fs::read_to_string(directory.join(".envrc")).unwrap(),
            "# Generated by Plainix\nuse flake\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn removes_generated_files_when_locking_fails() {
        let directory = temporary_directory("rollback");

        let error = initialize_with_lock(&directory, InitOptions { direnv: true }, |_| {
            Err("lock failed".to_owned())
        })
        .unwrap_err();

        assert_eq!(error, "lock failed");
        for file in ["plainix.nix", "flake.nix", "flake.lock", ".envrc"] {
            assert!(!directory.join(file).exists());
        }
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn refuses_to_replace_existing_project_files() {
        let directory = temporary_directory("existing");
        fs::write(directory.join("plainix.nix"), "original project\n").unwrap();

        let error = initialize_with_lock(&directory, InitOptions::default(), |_| {
            panic!("lock must not run when a project file already exists")
        })
        .unwrap_err();

        assert!(error.contains("refusing to overwrite"));
        assert_eq!(
            fs::read_to_string(directory.join("plainix.nix")).unwrap(),
            "original project\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn preserves_existing_envrc() {
        let directory = temporary_directory("envrc");
        fs::write(directory.join(".envrc"), "source_env custom.envrc\n").unwrap();

        let result = initialize_with_lock(&directory, InitOptions { direnv: true }, |path| {
            fs::write(path.join("flake.lock"), "{}\n").map_err(|error| error.to_string())
        })
        .unwrap();

        assert_eq!(result.envrc, EnvrcResult::KeptExisting);
        assert!(result.packages.is_empty());
        assert!(
            fs::read_to_string(directory.join("plainix.nix"))
                .unwrap()
                .contains("packages = [ ];")
        );
        assert_eq!(
            fs::read_to_string(directory.join(".envrc")).unwrap(),
            "source_env custom.envrc\n"
        );
        fs::remove_dir_all(directory).unwrap();
    }
}
