import contextlib
import io
import subprocess
import tempfile
import unittest
from pathlib import Path

import plainix
from plainix import PlainixError


def preset(tool):
    return next(item for item in plainix.PRESETS if item["id"] == tool)


def fake_lock(directory):
    (directory / "flake.lock").write_text("{}\n")


def failing_lock(_directory):
    raise PlainixError("lock failed")


class ProjectTestCase(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.directory = Path(temporary.name)

    def read(self, name):
        return (self.directory / name).read_text()


class ArgumentTests(unittest.TestCase):
    def parse(self, *arguments):
        return plainix.build_parser().parse_args(arguments)

    def rejects(self, *arguments):
        with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit):
            self.parse(*arguments)

    def test_no_arguments_has_no_command(self):
        self.assertIsNone(self.parse().command)

    def test_init_without_options_is_interactive(self):
        options = self.parse("init")
        self.assertFalse(options.empty)
        self.assertIsNone(options.tools)

    def test_parses_explicit_tools(self):
        options = self.parse("init", "--with", "godot", "--with=blender")
        self.assertEqual(options.tools, ["godot", "blender"])

    def test_parses_empty_environment(self):
        self.assertTrue(self.parse("init", "--empty").empty)

    def test_rejects_invalid_init_options(self):
        self.rejects("init", "--with")
        self.rejects("init", "--empty", "--with", "rust")
        self.rejects("init", "--direnv")

    def test_parses_update(self):
        self.assertEqual(self.parse("update").command, "update")
        self.rejects("update", "--force")


class PresetTests(unittest.TestCase):
    def test_combines_application_presets(self):
        presets = plainix.resolve(["godot", "blender"], "x86_64-linux")
        self.assertEqual(plainix.packages_for(presets), ["godot_4", "blender"])

    def test_combines_presets_without_duplicate_packages(self):
        first = {"packages": ["shared", "first"]}
        second = {"packages": ["shared", "second"]}
        self.assertEqual(
            plainix.packages_for([first, second, first]),
            ["shared", "first", "second"],
        )

    def test_resolve_drops_repeated_tools(self):
        self.assertEqual(
            plainix.resolve(["rust", "rust"], "x86_64-linux"), [preset("rust")]
        )

    def test_rejects_unknown_and_unsupported_presets(self):
        with self.assertRaises(PlainixError):
            plainix.resolve(["unknown"], "x86_64-linux")
        with self.assertRaises(PlainixError):
            plainix.resolve(["freecad"], "aarch64-darwin")
        self.assertNotIn(preset("freecad"), plainix.available_for("aarch64-darwin"))

    def test_empty_selection_has_no_packages(self):
        self.assertEqual(plainix.packages_for([]), [])

    def test_maps_supported_platforms(self):
        self.assertEqual(plainix.current_system("x86_64", "Linux"), "x86_64-linux")
        self.assertEqual(plainix.current_system("arm64", "Darwin"), "aarch64-darwin")
        with self.assertRaises(PlainixError):
            plainix.current_system("riscv64", "Linux")

    def test_menu_starts_with_the_empty_choice(self):
        menu = plainix.selection_menu("x86_64-linux").splitlines()
        self.assertTrue(menu[0].startswith(f"{plainix.NO_TOOLS}\t"))
        self.assertTrue(any(line.startswith("rust\t") for line in menu))

    def test_parse_selection(self):
        self.assertEqual(plainix.parse_selection("none\t(none)\n"), [])
        self.assertEqual(plainix.parse_selection("go\tGo\nzig\tZig\n"), ["go", "zig"])


class InitTests(ProjectTestCase):
    def initialize(self, presets=(), git_repository=False, lock=fake_lock):
        return plainix.initialize(self.directory, list(presets), git_repository, lock)

    def test_generates_selected_tools_and_lock(self):
        result = self.initialize([preset("rust")])

        generated = self.read("plainix.nix")
        self.assertIn("# Initial tools: Rust", generated)
        self.assertIn('"rustc"', generated)
        self.assertIn('"aarch64-darwin"', generated)
        self.assertIn(plainix.NIXPKGS_INPUT, generated)
        self.assertIn(plainix.PACKAGE_SEARCH_URL, generated)
        self.assertTrue(result.envrc_created)
        self.assertIsNone(result.gitignore)
        self.assertFalse((self.directory / ".gitignore").exists())
        self.assertTrue((self.directory / "flake.lock").is_file())
        self.assertEqual(self.read(".envrc"), "# Generated by Plainix\nuse flake\n")

    def test_limits_systems_to_those_every_preset_supports(self):
        result = self.initialize([preset("rust"), preset("freecad")])

        self.assertEqual(result.systems, ["x86_64-linux", "aarch64-linux"])
        self.assertNotIn("aarch64-darwin", self.read("plainix.nix"))

    def test_removes_generated_files_when_locking_fails(self):
        with self.assertRaisesRegex(PlainixError, "lock failed"):
            self.initialize(lock=failing_lock)

        for file in ("plainix.nix", "flake.nix", "flake.lock", ".envrc"):
            self.assertFalse((self.directory / file).exists())

    def test_refuses_to_replace_existing_project_files(self):
        (self.directory / "plainix.nix").write_text("original project\n")

        with self.assertRaisesRegex(PlainixError, "refusing to overwrite"):
            self.initialize(lock=lambda _: self.fail("lock must not run"))

        self.assertEqual(self.read("plainix.nix"), "original project\n")

    def test_preserves_existing_envrc(self):
        (self.directory / ".envrc").write_text("source_env custom.envrc\n")

        result = self.initialize()

        self.assertFalse(result.envrc_created)
        self.assertEqual(result.packages, [])
        self.assertIn("packages = [ ];", self.read("plainix.nix"))
        self.assertEqual(self.read(".envrc"), "source_env custom.envrc\n")

    def test_prepares_git_files_without_staging_contents(self):
        subprocess.run(["git", "init", "--quiet"], cwd=self.directory, check=True)
        (self.directory / ".gitignore").write_text("/target\n")

        result = self.initialize(git_repository=True)

        self.assertIsNone(result.git_error)
        for file in ("plainix.nix", "flake.nix", "flake.lock", ".envrc", ".gitignore"):
            self.assertIn(file, result.git_files)
            subprocess.run(
                ["git", "ls-files", "--error-unmatch", "--", file],
                cwd=self.directory,
                check=True,
                capture_output=True,
            )
        subprocess.run(
            ["git", "diff", "--cached", "--quiet"], cwd=self.directory, check=True
        )
        self.assertIn(".direnv/\n", self.read(".gitignore"))

    def test_updates_gitignore_once(self):
        path = self.directory / ".gitignore"
        path.write_text("/target")

        self.assertEqual(plainix.ensure_gitignore(path), "updated")
        self.assertEqual(path.read_text(), "/target\n.direnv/\n")
        self.assertEqual(plainix.ensure_gitignore(path), "present")

    def test_leaves_gitignore_unchanged_when_locking_fails(self):
        path = self.directory / ".gitignore"
        path.write_text("/target\n")

        with self.assertRaises(PlainixError):
            self.initialize(git_repository=True, lock=failing_lock)

        self.assertEqual(path.read_text(), "/target\n")


class UpdateTests(ProjectTestCase):
    def setUp(self):
        super().setUp()
        for file in ("plainix.nix", "flake.nix"):
            (self.directory / file).write_text("{ }\n")
        (self.directory / "flake.lock").write_text("old\n")

    @staticmethod
    def write_new_lock(directory):
        (directory / "flake.lock").write_text("new\n")

    @staticmethod
    def succeed(_directory):
        pass

    def test_keeps_new_lock_when_verification_passes(self):
        self.assertTrue(
            plainix.update(self.directory, self.write_new_lock, self.succeed)
        )
        self.assertEqual(self.read("flake.lock"), "new\n")

    def test_restores_lock_when_verification_fails(self):
        def broken(_directory):
            raise PlainixError("broken")

        with self.assertRaisesRegex(PlainixError, "broken\n.*restored"):
            plainix.update(self.directory, self.write_new_lock, broken)

        self.assertEqual(self.read("flake.lock"), "old\n")

    def test_restores_lock_when_update_fails(self):
        def offline(directory):
            self.write_new_lock(directory)
            raise PlainixError("offline")

        with self.assertRaisesRegex(PlainixError, "offline\n.*restored"):
            plainix.update(
                self.directory,
                offline,
                lambda _: self.fail("verification must not run"),
            )

        self.assertEqual(self.read("flake.lock"), "old\n")

    def test_restores_lock_when_interrupted(self):
        def interrupted(_directory):
            raise KeyboardInterrupt

        with self.assertRaises(KeyboardInterrupt):
            plainix.update(self.directory, self.write_new_lock, interrupted)

        self.assertEqual(self.read("flake.lock"), "old\n")

    def test_reports_when_lock_is_unchanged(self):
        self.assertFalse(plainix.update(self.directory, self.succeed, self.succeed))

    def test_refuses_directories_without_a_project(self):
        (self.directory / "plainix.nix").unlink()

        with self.assertRaisesRegex(PlainixError, "plainix.nix"):
            plainix.update(
                self.directory, lambda _: self.fail("must not update"), self.succeed
            )


if __name__ == "__main__":
    unittest.main()
